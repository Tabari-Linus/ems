import type { CodegenConfig } from '@graphql-codegen/cli';

/**
 * GraphQL Code Generator: typed Apollo Angular services from the backend schema files.
 * The schema is read from disk (no running server needed). There is no single root file:
 * `root.graphqls` declares `Query`/`Mutation` and every other file uses `extend type`,
 * so the glob must load all of them together.
 */
const config: CodegenConfig = {
  overwrite: true,
  schema: '../backend/src/main/resources/graphql/**/*.graphqls',
  documents: ['src/app/**/*.graphql'],
  ignoreNoDocuments: false,
  generates: {
    'src/app/graphql/generated.ts': {
      // typescript-operations v6 is self-contained: it emits the scalar, enum and input
      // types each operation needs. Adding the `typescript` plugin as well would declare
      // them twice (TS2300 duplicate identifier), so it is intentionally not used.
      plugins: [
        { add: { content: '/* eslint-disable */\n// Generated by `npm run codegen`. Do not edit.' } },
        'typescript-operations',
        'typescript-apollo-angular',
      ],
      config: {
        strictScalars: true,
        scalars: {
          ID: 'string',
          Date: 'string',
          DateTime: 'string',
          BigDecimal: 'string',
        },
        useTypeImports: true,
        addExplicitOverride: true,
      },
    },
  },
  hooks: {
    afterAllFileWrite: ['prettier --write'],
  },
};

export default config;
